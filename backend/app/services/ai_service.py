    async def _auto_detect_mode(
        self,
        question: str,
        extra_context: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Smart auto-detect: classifies the question and generates an optimal response plan.
        Returns dict with 'detected_mode', 'confidence', and 'response_plan'.
        """
        logger.info("Running smart auto-detect classifier...")
        
        classifier_input = f"ВОПРОС ПОЛЬЗОВАТЕЛЯ:\n{question}"
        if extra_context:
            classifier_input += f"\n\nКОНТЕКСТ ЗАДАЧИ:\n{extra_context[:2000]}"
        
        try:
            response = await self.client.messages.create(
                model=self.settings.claude_haiku_model,
                max_tokens=1024,
                system=AUTO_DETECT_CLASSIFIER_PROMPT,
                messages=[{"role": "user", "content": classifier_input}]
            )
            
            # Extract text from response
            raw_text = ""
            for block in response.content:
                if block.type == "text":
                    raw_text += block.text
            
            raw_text = raw_text.strip()
            # Extract JSON from response (handle markdown code blocks)
            if "```" in raw_text:
                parts = raw_text.split("```")
                for part in parts:
                    if part.strip().startswith("json"):
                        raw_text = part.strip()[4:].strip()
                        break
                    elif part.strip().startswith("{"):
                        raw_text = part.strip()
                        break
            
            if "{" not in raw_text and "}" not in raw_text:
                 # Fallback if no JSON found
                 raise ValueError("No JSON found in response")

            # Try to find the JSON object if there's extra text
            start = raw_text.find("{")
            end = raw_text.rfind("}")
            if start != -1 and end != -1:
                raw_text = raw_text[start:end+1]

            result = json.loads(raw_text)
            detected_mode = result.get("detected_mode", "consultant")
            confidence = float(result.get("confidence", 0.5))
            response_plan = result.get("response_plan", "")
            
            # Validate detected mode exists
            if detected_mode not in CHAT_MODE_PROMPTS:
                logger.warning(f"Auto-detect returned unknown mode '{detected_mode}', falling back to consultant")
                detected_mode = "consultant"
            
            # Require minimum confidence
            if confidence < 0.7:
                logger.info(f"Auto-detect confidence {confidence:.2f} below threshold, using consultant")
                detected_mode = "consultant"
            
            logger.info(f"Auto-detect result: mode='{detected_mode}', confidence={confidence:.2f}, plan_length={len(response_plan)}")
            
            return {
                "detected_mode": detected_mode,
                "confidence": confidence,
                "response_plan": response_plan
            }
            
        except Exception as e:
            logger.error(f"Auto-detect failed: {e}")
            return {
                "detected_mode": "consultant",
                "confidence": 0.0,
                "response_plan": ""
            }

    async def query_with_rag(
        self, 
        question: str, 
        history: Optional[List[Dict[str, str]]] = None,
        top_k: int = DEFAULT_TOP_K,
        chat_mode: str = 'consultant',
        extra_context: Optional[str] = None,
        progress_callback: Optional[Callable[[str], Awaitable[None]]] = None,
        user_id: Optional[int] = None
    ) -> Dict[str, Any]:
        """
        Enhanced RAG with Claude 3.5 Haiku and Extended Thinking.
        """
        logger.info(f"=== AI SERVICE (CLAUDE): query_with_rag ===")
        logger.info(f"Question: {question[:100]}...")
        logger.info(f"Chat mode: {chat_mode}")
        
        # ═══════════════════════════════════════════════════════════════
        # PHASE 0: SMART AUTO-DETECT (if mode is 'auto-detect')
        # ═══════════════════════════════════════════════════════════════
        
        auto_detect_plan = ""
        if chat_mode == 'auto-detect':
            if progress_callback:
                await progress_callback("detecting_mode")
            detect_result = await self._auto_detect_mode(question, extra_context)
            chat_mode = detect_result["detected_mode"]
            auto_detect_plan = detect_result.get("response_plan", "")
            logger.info(f"Auto-detected mode: '{chat_mode}', plan: '{auto_detect_plan[:100]}...'")
        
        # Select appropriate system prompt
        system_prompt = self._get_system_prompt(chat_mode)
        
        # For simple modes, use simplified query
        if chat_mode in SIMPLE_MODES:
            return await self._simple_query(question, history, chat_mode, system_prompt, user_id=user_id)
        
        # ═══════════════════════════════════════════════════════════════
        # PHASE 1: SEARCH FOR CONTEXT
        # ═══════════════════════════════════════════════════════════════
        
        search_query = question
        if extra_context:
            ctx_keywords = extract_search_keywords(extra_context[:2000])
            if ctx_keywords:
                search_query = f"{question} {' '.join(ctx_keywords[:10])}"
                logger.info(f"Augmented search query with context keywords: {search_query}")

        logger.info("Running search for context...")
        if progress_callback:
            await progress_callback("searching")
        
        # Use enhanced retrieval from existing implementation
        results = await self._enhanced_retrieve_context(
            search_query, 
            top_k=top_k
        )
        
        # Calculate simplified quality metrics for compatibility
        quality_results = [r for r in results if r.get('similarity', 0) >= MIN_RELEVANCE_SCORE]
        similarities = [r.get('similarity', 0) for r in quality_results]
        avg_sim = sum(similarities) / len(similarities) if similarities else 0
        high_q = sum(1 for s in similarities if s >= HIGH_QUALITY_THRESHOLD)
        medium_q = sum(1 for s in similarities if MEDIUM_QUALITY_THRESHOLD <= s < HIGH_QUALITY_THRESHOLD)
        low_q = sum(1 for s in similarities if MIN_RELEVANCE_SCORE <= s < MEDIUM_QUALITY_THRESHOLD)
        
        quality_metrics = {
            'agentic_search_results': len(quality_results),
            'high_quality_results': high_q,
            'medium_quality_results': medium_q,
            'low_quality_results': low_q,
            'avg_relevance_score': avg_sim
        }
        
        # Format context
        context_str = self._format_enhanced_context(results)
        unique_sources = self._format_sources_with_quality(results)
        
        # ═══════════════════════════════════════════════════════════════
        # PHASE 3: FINAL SYNTHESIS
        # ═══════════════════════════════════════════════════════════════
        
        anthropic_history = self._convert_history_to_anthropic(history)
        
        final_prompt = self._build_final_prompt(
            question,
            context_str,
            extra_context,
            quality_metrics
        )
        if auto_detect_plan:
             final_prompt += f"\n\n### 📋 ПЛАН ОТВЕТА (ОБЯЗАТЕЛЬНО СЛЕДУЙТЕ):\n{auto_detect_plan}\n"

        logger.info(f"Phase 3: Streaming final response with Claude...")
        if progress_callback:
            await progress_callback("synthesizing")
        
        # Add current query with context
        messages = anthropic_history + [{"role": "user", "content": final_prompt}]
        
        async def stream_response():
            try:
                # Use extended thinking as requested
                async with self.client.messages.stream(
                    model=self.settings.claude_haiku_model,
                    max_tokens=16000,
                    system=system_prompt,
                    thinking={
                        "type": "enabled",
                        "budget_tokens": self.settings.thinking_budget_tokens
                    },
                    messages=messages,
                ) as stream:
                    async for text in stream.text_stream:
                        yield text
                    
                    # Track usage for RAG synthesis
                    try:
                        final_message = await stream.get_final_message()
                        if hasattr(final_message, 'usage'):
                            usage = final_message.usage
                            await UsageService.track_usage_async(
                                user_id=user_id,
                                model_name=self.settings.claude_haiku_model,
                                input_tokens=usage.input_tokens,
                                output_tokens=usage.output_tokens,
                                request_type=f"chat_rag_{chat_mode}"
                            )
                    except Exception as usage_err:
                        logger.warning(f"Failed to track RAG usage: {usage_err}")
            except Exception as e:
                logger.error(f"Streaming error: {e}")
                yield f"\n\n⚠️ Error generating response: {str(e)}"
        
        return {
            "response": stream_response(),
            "sources": unique_sources,
            "quality_metrics": quality_metrics,
            "search_rounds": [], # Legacy field for frontend compatibility
        }

    async def _enhanced_retrieve_context(
        self, 
        query: str, 
        top_k: int = DEFAULT_TOP_K,
        filter_source: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Advanced retrieval with hybrid search, multi-query expansion, and re-ranking.
        """
        filter_metadata = {"source": filter_source} if filter_source else None
        
        # ── Step 1: Generate query variants ──
        query_variants = [query]
        
        # Fast dictionary translation (no LLM call)
        dict_translated = fast_translate_to_uzbek(query)
        if dict_translated != query and dict_translated.lower() != query.lower():
            query_variants.append(dict_translated)
            logger.info(f"Dict-translated query: '{query}' → '{dict_translated}'")
        
        # Extract Uzbek keywords for targeted keyword search
        uzbek_keywords = extract_search_keywords(query)
        if uzbek_keywords:
            keyword_query = " ".join(uzbek_keywords)
            if keyword_query not in query_variants:
                query_variants.append(keyword_query)
                logger.info(f"Keyword query: '{keyword_query}'")
        
        # LLM translation as fallback
        dict_coverage = sum(1 for w in query.lower().split() if w in LEGAL_TERMINOLOGY_RU_UZ)
        if dict_coverage < len(query.split()) * 0.3:
            try:
                llm_translated = await self._translate_to_uzbek(query)
                if llm_translated and llm_translated != query and llm_translated not in query_variants:
                    query_variants.append(llm_translated)
                    logger.info(f"LLM-translated query: '{llm_translated}'")
            except Exception as e:
                logger.warning(f"LLM translation failed: {e}")
        
        logger.info(f"Search with {len(query_variants)} query variants")
        
        # ── Step 2: Run hybrid search for each variant ──
        all_results = []
        per_variant_k = max(top_k, 60)
        
        for variant in query_variants:
            try:
                results = await self.vector_store.ahybrid_search(
                    variant,
                    top_k=per_variant_k,
                    filter_metadata=filter_metadata,
                    semantic_weight=0.6,
                    keyword_weight=0.4,
                )
                all_results.extend(results)
            except Exception as e:
                logger.warning(f"Search failed for variant '{variant[:50]}': {e}")
        
        # ── Step 3: Merge and deduplicate ──
        seen_keys = {}
        for result in all_results:
            metadata = result.get("metadata", {})
            content = result.get("content", "")
            key = f"{metadata.get('source', '')}_{metadata.get('article_display', '')}_{hash(content[:200])}"
            
            if key not in seen_keys or result.get("similarity", 0) > seen_keys[key].get("similarity", 0):
                seen_keys[key] = result
        
        merged = sorted(seen_keys.values(), key=lambda x: x.get("similarity", 0), reverse=True)
        
        # ── Step 4: Apply primary code boosting ──
        for result in merged:
            source_name = result.get("metadata", {}).get("source", "")
            source_check = source_name.replace("_", " ")
            if any(code in source_check for code in PRIMARY_CODES_KEYWORDS):
                current_sim = result.get("similarity", 0)
                result["similarity"] = min(0.99, current_sim * 1.15)
                result["is_primary"] = True
        
        merged = sorted(merged, key=lambda x: x.get("similarity", 0), reverse=True)
        
        # ── Step 5: Re-rank top candidates with Voyage AI ──
        rerank_candidates = merged[:min(top_k * 2, 150)]
        
        if len(rerank_candidates) > 5:
            try:
                reranked = await self.vector_store.arerank(
                    query,  # Use original query for reranking
                    rerank_candidates,
                    top_k=top_k,
                )
                for result in reranked:
                    source_name = result.get("metadata", {}).get("source", "")
                    source_check = source_name.replace("_", " ")
                    if any(code in source_check for code in PRIMARY_CODES_KEYWORDS):
                        current_sim = result.get("similarity", 0)
                        result["similarity"] = min(0.99, current_sim * 1.10)
                        result["is_primary"] = True
                
                reranked = sorted(reranked, key=lambda x: x.get("similarity", 0), reverse=True)
                logger.info(f"Reranked {len(reranked)} results")
                return reranked[:top_k]
            except Exception as e:
                logger.warning(f"Reranking failed, using hybrid results: {e}")
        
        return merged[:top_k]
    
    def _format_enhanced_context(self, results: List[Dict[str, Any]]) -> str:
        if not results:
            return "⚠️ No relevant legal documents found meeting quality threshold."
        
        context_parts = []
        for i, result in enumerate(results, 1):
            metadata = result.get("metadata", {})
            content = result.get("content", "")
            similarity = result.get("similarity", 0)
            
            if similarity >= HIGH_QUALITY_THRESHOLD:
                quality_icon = "🟢"
                quality_label = "HIGH"
            elif similarity >= MEDIUM_QUALITY_THRESHOLD:
                quality_icon = "🟡"
                quality_label = "MEDIUM"
            else:
                quality_icon = "🟠"
                quality_label = "LOW"
            
            source_filename = metadata.get("source", "Unknown")
            code_name = self._get_source_title(source_filename)
            article = metadata.get("article_display", metadata.get("article_number", "Unknown"))
            chapter = metadata.get("chapter", "")
            section = metadata.get("section", "")
            title = metadata.get("title", "")
            
            is_primary = result.get("is_primary", False)
            primary_badge = "⭐️ PRIMARY SOURCE" if is_primary else ""
            
            context_parts.append(
                f"[{quality_icon} Source {i} | Relevance: {similarity:.1%} ({quality_label}) {primary_badge}]\n"
                f"📚 Источник: {code_name}\n"
                f"📋 Статья: {article}\n"
                f"📂 Раздел: {section}\n"
                f"📖 Глава: {chapter}\n"
                f"📝 Название: {title}\n"
                f"───────────────────────────────────────────\n"
                f"{content}\n"
                f"───────────────────────────────────────────"
            )
        return "\n\n".join(context_parts)
    
    def _format_sources_with_quality(self, results: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        sources = []
        for idx, result in enumerate(results):
            metadata = result.get("metadata", {})
            similarity = result.get("similarity", 0)
            
            if similarity >= HIGH_QUALITY_THRESHOLD:
                quality_level = "high"
            elif similarity >= MEDIUM_QUALITY_THRESHOLD:
                quality_level = "medium"
            else:
                quality_level = "low"
            
            article = metadata.get("article_display", metadata.get("article_number", "Unknown"))
            source_filename = metadata.get("source", "Unknown")
            code_name = self._get_source_title(source_filename)
            
            sources.append({
                "id": f"source-{idx}",
                "article": article,
                "source": code_name,
                "source_filename": source_filename,
                "chapter": metadata.get("chapter", "")[:80],
                "title": metadata.get("title", "")[:100],
                "preview": result.get("content", "")[:300] + "...",
                "similarity": f"{similarity * 100:.1f}%",
                "quality_level": quality_level,
            })
        return sources
    
    def _get_source_title(self, source_filename: str) -> str:
        if not source_filename or source_filename == "Unknown":
            return "Unknown"
        base_name = source_filename.rsplit('.', 1)[0]
        clean_name = base_name.lstrip('-_')
        if '_' in clean_name:
            parts = clean_name.split('_', 1)
            if parts[0].isdigit() or (len(parts[0]) > 2 and any(c.isdigit() for c in parts[0])):
                title = parts[1]
            else:
                title = clean_name
        else:
            title = clean_name
        return title.replace('_', ' ')

