    async def analyze_contract(
        self,
        contract_text: str
    ) -> Dict[str, Any]:
        """
        Analyze a contract for legal compliance using Gemini Flash.
        Returns structured audit result with validity score, errors, warnings, and missing clauses.
        """
        logger.info(f"=== ANALYZE CONTRACT ===")
        logger.info(f"Contract text length: {len(contract_text)} chars")
        
        # Retrieve legal context for contract analysis
        try:
            self._init_rag_engine()
            context_results = await self._enhanced_retrieve_context(
                query="существенные условия договора обязательные требования гражданский кодекс",
                top_k=70
            )
            legal_context = self._format_enhanced_context(context_results)
            sources = self._format_sources_with_quality(context_results)
        except Exception as e:
            logger.warning(f"RAG retrieval failed for contract analysis: {e}")
            legal_context = "Правовой контекст недоступен."
            sources = []
        
        # Build the audit prompt with the contract text and legal context
        audit_prompt = CONTRACT_AUDIT_PROMPT.format(
            context=legal_context,
            contract_text=contract_text
        )
        
        try:
            response = await self.client.aio.models.generate_content(
                model="gemini-3-pro-preview",
                contents=audit_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=VALIDATOR_PROMPT,
                    temperature=0.2,
                    max_output_tokens=MAX_OUTPUT_TOKENS,
                    thinking_config=types.ThinkingConfig(
                        thinking_level="high"
                    ),
                )
            )
            
            raw_text = response.text.strip() if response.text else ""
            
            # Extract JSON from response (handle markdown code blocks)
            json_text = raw_text
            if "```" in json_text:
                parts = json_text.split("```")
                for part in parts:
                    stripped = part.strip()
                    if stripped.startswith("json"):
                        stripped = stripped[4:].strip()
                    if stripped.startswith("{"):
                        json_text = stripped
                        break
            
            audit = json.loads(json_text)
            
            logger.info(f"Contract analysis complete. Score: {audit.get('validity_score', 'N/A')}")
            
            return {
                "audit": audit,
                "sources": sources,
                "raw_response": raw_text,
            }
            
        except json.JSONDecodeError as e:
            logger.error(f"Failed to parse contract audit JSON: {e}")
            logger.error(f"Raw response: {raw_text[:500]}")
            # Return a fallback audit
            return {
                "audit": {
                    "validity_score": 0,
                    "score_explanation": "Не удалось выполнить автоматический анализ. Попробуйте снова.",
                    "critical_errors": [],
                    "warnings": [],
                    "missing_clauses": [],
                    "summary": raw_text[:1000] if raw_text else "Ошибка анализа"
                },
                "sources": sources,
                "raw_response": raw_text,
            }
        except Exception as e:
            logger.error(f"Contract analysis error: {e}")
            raise

    async def analyze_document(
        self,
        document_text: str,
        document_type: str,
        top_k: int = 50
    ) -> Dict[str, Any]:
        """
        Analyze document using Legacy Logic (Deep Multi-Check).
        """
        logger.info(f"=== ANALYZE DOCUMENT (LEGACY) ===")
        
        # 1. Extract topics
        search_queries = self._extract_document_topics(document_text, document_type)
        
        # 2. Retrieve context
        all_results = []
        seen_articles = set()
        
        # Targeted searches
        for search_query in search_queries:
            results = await self.vector_store.asearch(search_query, top_k=15)
            for result in results:
                article_key = f"{result.get('metadata', {}).get('source')}_{result.get('metadata', {}).get('article_display')}"
                if article_key not in seen_articles:
                    seen_articles.add(article_key)
                    all_results.append(result)
        
        # Broad document validation searches (from Legacy)
        broad_searches = [
            # Core document requirements
            "доверенность полномочия представитель",
            "форма документа обязательные реквизиты",
            "сроки действия документа",
            "подпись печать удостоверение",
            "недействительность ничтожность",
            # Up-to-dateness specific searches
            "актуальность законодательства изменения",
            "утратил силу недействующий",
            "новая редакция изменения дополнения",
            # Procedural
            "порядок оформления регистрация",
            "государственная пошлина сбор",
            "сроки исковой давности",
        ]
        
        for broad_query in broad_searches:
            results = await self.vector_store.asearch(broad_query, top_k=5)
            for result in results:
                article_key = f"{result.get('metadata', {}).get('source')}_{result.get('metadata', {}).get('article_display')}"
                if article_key not in seen_articles:
                    seen_articles.add(article_key)
                    all_results.append(result)
                    
        # Sort and limit
        all_results.sort(key=lambda x: x.get("similarity", 0), reverse=True)
        final_results = all_results[:top_k]
        
        legal_context = self._format_enhanced_context(final_results)
        sources = self._format_sources_with_quality(final_results)
        
        # 3. Analyze with AI
        type_hint = f"Тип документа: {document_type}" if document_type else "Тип документа: не указан"
        audit_prompt = DOCUMENT_AUDIT_PROMPT.format(
            context=legal_context,
            document_text=document_text[:30000],
            document_type=type_hint
        )
        
        try:
            response = await self.client.aio.models.generate_content(
                model=self.settings.gemini_flash_model,
                contents=audit_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=DOCUMENT_VALIDATOR_PROMPT,
                    temperature=0.1,
                    max_output_tokens=MAX_OUTPUT_TOKENS,
                    thinking_config=types.ThinkingConfig(thinking_level="high"),
                )
            )
            
            raw_text = response.text
            audit = self._parse_document_audit_response(raw_text)
            
            return {
                "audit": audit,
                "sources": sources,
                "raw_response": raw_text
            }
        except Exception as e:
            logger.error(f"Analyze document fatal error: {e}")
            raise
